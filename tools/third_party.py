"""Write THIRD_PARTY_LICENSES.md for the shipped binaries (twm, twmctl,
twm-settings): every crate compiled into them for Windows x64, its declared
licence, and the licence files from its source package.

    python tools/third_party.py [output]
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TARGET = "x86_64-pc-windows-msvc"
SHIPPED = ["twm", "twmctl", "twm-settings"]
OWN = {"twm", "twmctl", "twm-settings", "twm-core", "twm-testwin", "platform-probe"}


def run(*args):
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8").stdout


def main():
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "THIRD_PARTY_LICENSES.md"
    used = set()
    for p in SHIPPED:
        tree = run("cargo", "tree", "--offline", "-p", p, "-e", "normal", "--target", TARGET, "--prefix", "none", "--format", "{p}")
        for line in tree.splitlines():
            parts = line.split()
            if len(parts) >= 2:
                used.add((parts[0], parts[1].lstrip("v")))
    meta = json.loads(run("cargo", "metadata", "--offline", "--format-version", "1"))
    pkgs = {(p["name"], p["version"]): p for p in meta["packages"]}
    rows, texts = [], []
    for name, ver in sorted(used):
        if name in OWN:
            continue
        p = pkgs.get((name, ver))
        if p is None:
            raise SystemExit(f"{name} {ver} not in cargo metadata")
        lic = p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "UNKNOWN")
        rows.append(f"| {name} | {ver} | {lic} | {p.get('repository') or ''} |")
        src = pathlib.Path(p["manifest_path"]).parent
        files = sorted(f for f in src.iterdir() if f.is_file() and f.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE")))
        if not files:
            texts.append(f"### {name} {ver}\n\nThe package ships no licence file; its declared licence is {lic}. "
                         "The standard texts of these licences are reproduced in this file for other crates (e.g. `windows`).\n")
        for f in files:
            body = f.read_text(encoding="utf-8", errors="replace").strip()
            texts.append(f"### {name} {ver} — {f.name}\n\n```text\n{body}\n```\n")
    unknown = [r for r in rows if "UNKNOWN" in r]
    doc = [
        "# Third-party licences",
        "",
        "TilingWindowsManager's binaries (twm.exe, twmctl.exe, twm-settings.exe) include the following",
        f"Rust crates ({len(rows)} packages, generated by `tools/third_party.py` from `cargo tree` for {TARGET}).",
        "No source code from other window managers is included.",
        "",
        "| Crate | Version | Licence | Repository |",
        "|---|---|---|---|",
        *rows,
        "",
        "## Licence texts",
        "",
        *texts,
    ]
    out.write_text("\n".join(doc), encoding="utf-8", newline="\n")
    print(f"wrote {out}: {len(rows)} crates, {len(texts)} licence sections, {len(unknown)} without a declared licence")
    if unknown:
        print("\n".join(unknown))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
